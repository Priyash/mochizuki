"""Kaggle: free T4 GPUs, about 30 hours a week, driven through Kaggle's own command-line tool.

One batch is one Kaggle session (up to `kaggle.session_hours`). Its inputs travel as one private Kaggle
dataset, versioned per batch, with the worker inside; a small notebook (BOOTSTRAP) starts the worker.
Nothing here needs a Kaggle SDK.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
from pathlib import Path

from ...errors import BudgetUsedUp, ProviderError
from ...project import CONFIG_FILE
from ..base import WORKER_PACKAGES, Provider, Status

NAME = "kaggle"
SESSION_LIMIT_S = 12 * 3600          # Kaggle ends any session at 12 h
SESSION_GRACE_S = 1800               # a session's hard stop is this long past its planned hours
MIN_BATCH_S = 600                    # below this, a batch is not worth a session: Kaggle rests
DEFAULT_ACCELERATOR = "NvidiaTeslaT4"
QUOTA_ARGS = ["quota", "-v"]

BOOTSTRAP = '''# Generated by `python -m engine`. Runs on Kaggle; do not edit by hand.
import os, subprocess, sys, zipfile
BATCH_ID = {batch_id!r}
ENGINE_SET = {engine_set!r}
os.environ.setdefault("HF_HOME", "/tmp/hf")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

def find(name):
    for root, _, files in os.walk("/kaggle/input"):
        if name in files:
            return os.path.join(root, name)
    for root, _, files in os.walk("/kaggle/input"):
        for f in files:
            if f.endswith(".zip"):
                zipfile.ZipFile(os.path.join(root, f)).extractall("/tmp/in")
    for root, _, files in os.walk("/tmp/in"):
        if name in files:
            return os.path.join(root, name)
    raise SystemExit(name + " not found in /kaggle/input")

manifest = find("manifest.json")
worker = find("worker.py")
if ENGINE_SET == "gpu":
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", {packages}], check=True)
os.makedirs("/kaggle/working/out", exist_ok=True)
code = subprocess.run([sys.executable, worker, "--manifest", manifest, "--inputs", os.path.dirname(manifest),
                       "--out", "/kaggle/working/out", "--engine-set", ENGINE_SET,
                       "--expect-batch", BATCH_ID]).returncode
print("worker exit code", code)
'''


class KaggleError(ProviderError):
    """The kaggle command failed or said no."""


def settings(p) -> dict:
    """The film's config.json -> "kaggle", with the username from KAGGLE_USERNAME when the config has none."""
    k = dict(p.config.get(NAME, {}))
    if not k.get("username"):
        k["username"] = os.environ.get("KAGGLE_USERNAME", "")
    return k


def week_start(now: float | None = None) -> float:
    """Kaggle's GPU week resets on Saturday at 00:00 UTC (its quota reports refreshAt)."""
    now = time.time() if now is None else now
    t = time.gmtime(now)
    days_since_saturday = (t.tm_wday - 5) % 7
    midnight = now - (t.tm_hour * 3600 + t.tm_min * 60 + t.tm_sec)
    return midnight - days_since_saturday * 86400


def session_budget(p) -> float:
    k = settings(p)
    return k.get("session_hours", 10) * 3600 - k.get("setup_minutes", 25) * 60


class KaggleProvider(Provider):
    """Kaggle's free GPUs through the `kaggle` command. `runner` stands in for the command in tests."""

    name = NAME
    hands_over_when_queued = True    # a batch that sits in Kaggle's queue may go to another provider
    deadline_margin_s = 900.0        # Kaggle's session ends hard: the worker stops 15 min early
    capabilities: frozenset[str] = frozenset()   # T4s: fp16 only, so no Qwen stills or keyframes (they come out blank)
    LICENSES = ("unknown", "other", "copyright-authors")      # all keep every right with the owner

    def __init__(self, p=None, runner=None):
        super().__init__()
        self._run = runner or self._subprocess
        stages = settings(p).get("stages") if p is not None else None
        if stages:
            self.stages = tuple(stages)                # config kaggle.stages: only these run on Kaggle

    # ---- sizing a batch
    def budget(self, p, led) -> tuple[float, float]:
        """What the next session may use: a session's worth, inside this week's weekly_gpu_hours."""
        k = settings(p)
        setup = k.get("setup_minutes", 25) * 60
        used = led.gpu_seconds_since(week_start(), NAME)
        weekly = k.get("weekly_gpu_hours", 28) * 3600
        budget = min(session_budget(p), weekly - used - setup)
        if budget <= MIN_BATCH_S:
            raise BudgetUsedUp(f"this week's Kaggle GPU budget is used up ({used / 3600:.1f} h of "
                               f"{weekly / 3600:.0f} h); it resets Saturday 00:00 UTC")
        return budget, setup

    def refs(self, p) -> tuple[str, str]:
        k = settings(p)
        if not k["username"]:
            raise KaggleError(f"set kaggle.username in {CONFIG_FILE} (or KAGGLE_USERNAME)")
        return f"{k['username']}/{k['dataset_slug']}", f"{k['username']}/{k['kernel_slug']}"

    def accelerator_for(self, p) -> str:
        return settings(p).get("accelerator", DEFAULT_ACCELERATOR)

    def run_timeout(self, p, est_seconds: float) -> int:
        return int(min(SESSION_LIMIT_S, settings(p).get("session_hours", 10) * 3600 + SESSION_GRACE_S))

    def queue_patience_s(self, p) -> float | None:
        return settings(p).get("max_queue_hours", 3) * 3600

    def package(self, p, work: Path, batch_id: str, engine_set: str) -> None:
        """The dataset's metadata, and the notebook that starts the worker."""
        k = settings(p)
        dataset_ref, kernel_ref = self.refs(p)
        (work / "dataset" / "dataset-metadata.json").write_text(json.dumps(
            {"title": k["dataset_slug"], "id": dataset_ref, "licenses": [{"name": "unknown"}]}, indent=1))
        kern = work / "kernel"
        (kern / "bootstrap.py").write_text(BOOTSTRAP.format(
            batch_id=batch_id, engine_set=engine_set, packages=", ".join(repr(x) for x in WORKER_PACKAGES)))
        (kern / "kernel-metadata.json").write_text(json.dumps({
            "id": kernel_ref, "title": k["kernel_slug"], "code_file": "bootstrap.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
            "enable_internet": "true", "dataset_sources": [dataset_ref], "competition_sources": [],
            "kernel_sources": [], "model_sources": []}, indent=1))

    def account_check(self) -> dict | None:
        """Can we sign in, and how much GPU time is left? For the producer's status.json."""
        code, text = self._run(QUOTA_ARGS)
        out = {"ok": code == 0, "output": text.strip()[-600:]}
        for args in (["datasets", "list", "--mine"], ["kernels", "list", "--mine"], ["config", "view"]):
            code, text = self._run(args)
            out[" ".join(args)] = f"{code}: {text.strip()[-500:]}"
        return out

    # ---- talking to Kaggle
    @staticmethod
    def _subprocess(args: list[str]) -> tuple[int, str]:
        if not shutil.which("kaggle"):
            raise KaggleError("the kaggle command is missing: pip install kaggle")
        r = subprocess.run(["kaggle", *args], capture_output=True, text=True)
        return r.returncode, (r.stdout or "") + (r.stderr or "")

    def call(self, *args: str) -> str:
        code, out = self._run(list(args))
        self.log.append(f"kaggle {' '.join(args[:2])} -> {code}: {out.strip()[-400:]}")
        if code != 0 or "error" in out.lower():
            raise KaggleError(f"kaggle {' '.join(args[:3])} failed: {out.strip()[-500:]}")
        return out

    def dataset_status(self, ref: str) -> str:
        code, out = self._run(["datasets", "status", ref])
        self.last_status = f"{code}: {out.strip()[-300:]}"
        self.log.append(f"kaggle datasets status {ref} -> {self.last_status}")
        if code != 0 and ("404" in out or "403" in out or "not found" in out.lower()):   # Kaggle answers 403 for a dataset that does not exist
            return "missing"
        return out.strip().lower() if code == 0 else f"unknown ({out.strip()[-200:]})"

    def publish_dataset(self, folder: Path, ref: str, message: str) -> None:
        if self.dataset_status(ref) == "missing":
            meta_f = folder / "dataset-metadata.json"
            meta = json.loads(meta_f.read_text())
            for lic in self.LICENSES:
                meta["licenses"] = [{"name": lic}]
                meta_f.write_text(json.dumps(meta, indent=1))
                try:
                    self.call("datasets", "create", "-p", str(folder), "-q")
                    return
                except KaggleError as e:
                    if "license" not in str(e).lower():
                        raise
            raise KaggleError(f"Kaggle accepted none of the licences {self.LICENSES} for the private dataset")
        else:
            self.call("datasets", "version", "-p", str(folder), "-m", message, "-q")

    def wait_dataset_ready(self, ref: str, timeout: float = 900, poll: float = 15) -> None:
        end = time.time() + timeout
        while time.time() < end:
            st = self.dataset_status(ref)
            if "ready" in st:
                return
            if "error" in st:
                raise KaggleError(f"dataset {ref} failed to process: {st}")
            time.sleep(poll)
        raise KaggleError(f"dataset {ref} not ready after {timeout:.0f} s; last status "
                          f"{getattr(self, 'last_status', '?')}")

    def push(self, folder: Path, accelerator: str, timeout_s: int) -> str | None:
        self.call("kernels", "push", "-p", str(folder), "--accelerator", accelerator, "-t", str(timeout_s))
        return None                                # Kaggle finds the run by its notebook's name

    def status(self, ref: str, handle: str | None = None) -> str:
        code, out = self._run(["kernels", "status", ref])
        self.log.append(f"kaggle kernels status -> {code}: {out.strip()[-300:]}")
        if code != 0:
            gone = any(w in out.lower() for w in ("404", "403", "not found", "denied", "wrong kernel slug"))
            return Status.ERROR if gone else Status.UNKNOWN   # the notebook was deleted or is out of reach
        m = re.search(r'has status "([^"]+)"', out)
        s = (m.group(1) if m else out).lower()
        for word, st in (("complete", Status.COMPLETE), ("error", Status.ERROR), ("cancel", Status.CANCELLED),
                         ("running", Status.RUNNING), ("queued", Status.QUEUED)):
            if word in s:
                return st
        return Status.UNKNOWN

    def output(self, ref: str, dest: Path, handle: str | None = None) -> None:
        dest.mkdir(parents=True, exist_ok=True)
        self.call("kernels", "output", ref, "-p", str(dest), "-o", "-q")

    def cancel(self, ref: str, handle: str | None = None) -> None:
        """Stop a queued or running notebook. Kaggle has no cancel command, so the notebook is
        deleted (as kaggle-maint does); the next push makes it again."""
        self.call("kernels", "delete", ref, "-y")

    def gpu_hours_left(self) -> float | None:
        code, out = self._run(QUOTA_ARGS)
        if code != 0:
            return None
        for line in out.splitlines():
            parts = [x.strip() for x in line.split(",")]
            if parts and parts[0].upper() == "GPU" and len(parts) >= 3:
                try:
                    return float(parts[2].rstrip("h"))
                except ValueError:
                    return None
        return None
