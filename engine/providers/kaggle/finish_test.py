"""One shot's AI finish on a GPU, outside the ledger: the test of the finish engines, their guide passes
and their reference stills before any shot of the film is finished.

    python -m engine finish-test 1-05 --engine ai_finish,ai_finish_720 --controls depth,lines
    python -m engine finish-test 1-05 --engine ai_finish_720 --backend colab

Render the shot with its guides first (`cgi render 1-05 --size 1280x720 --guides`). Each engine and
guide is one job of one manifest, so one GPU session runs them all.

kaggle (free): the inputs (guide clips, the cut-out stills, the manifest and the worker) go up as one
archive to the release `finish-tests`; the notebook <user>/<film>-finish-test downloads it from there,
runs the worker and keeps its output.
colab (the owner's units: only when the owner has said yes): the inputs wait in the release `batches`
as colab-<test id>.tar.gz, where the scheduled Colab runner (colab-run.yml, every 30 minutes) takes them
as it takes any Colab batch: one VM, the GPUs and balance checks of colab.* in config.json. This test
never starts the runner itself. If no runner has taken them in time, they are taken down again.

Back here, each finish is laid beside its guide and the 3D render, and a frame from its middle beside
the stills it was painted from; all of it goes to the release `finish-tests`. Nothing here reads or
writes the ledger, so Colab units a test uses are not in the producer's count of colab.total_cap_units:
the summary reports them.
"""
