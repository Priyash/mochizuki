"""One shot's AI finish on a Kaggle T4, outside the ledger: the test of a finish engine, its guide passes
and its reference stills before any shot of the film is finished.

    python -m engine finish-test 1-05 --engine ai_finish --controls depth,lines

Render the shot with its guides first (`cgi render 1-05 --size 1280x720 --guides`). Each guide is one job
of one manifest. The inputs (guide clips, the cut-out stills, the manifest and the worker) go up as one
archive to the release `finish-tests`; the notebook <user>/<film>-finish-test downloads it from there,
runs the worker and keeps its output. Back here, each finish is laid beside its guide and the 3D render,
and a frame from its middle beside the stills it was painted from; all of it goes to the same release.
Nothing here reads or writes the ledger.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import tarfile
import time
from pathlib import Path

from ... import steps
from ...cgi import config as cgi_config
from ...project import Project
from ...scheduler.batches import pack
from ..base import WORKER_PACKAGES
from ..release import Release
from .provider import DEFAULT_ACCELERATOR, NAME, KaggleError, settings

RELEASE = "finish-tests"
NOTES = ("AI finish tests, one shot at a time, outside the production ledger (python -m engine finish-test, "
         ".github/workflows/finish-test.yml): each test's inputs, finished clips, side-by-sides and log.")
TILE = (640, 360)              # each picture's size in a side-by-side video

SCRIPT = '''# {film} AI finish test {test_id}. Generated by `python -m engine finish-test`; do not edit.
import os, shutil, subprocess, sys, tarfile, urllib.request
os.environ.setdefault("HF_HOME", "/tmp/hf")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
os.makedirs("/tmp/in", exist_ok=True)
urllib.request.urlretrieve({url!r}, "/tmp/inputs.tar.gz")
with tarfile.open("/tmp/inputs.tar.gz") as t:
    t.extractall("/tmp/in")
for tool in (["nvidia-smi"], ["free", "-g"], ["df", "-h", "/tmp", "/kaggle/working"]):
    if shutil.which(tool[0]):
        subprocess.run(tool)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", {packages}], check=True)
os.makedirs("/kaggle/working/out", exist_ok=True)
code = subprocess.run([sys.executable, "/tmp/in/worker.py", "--manifest", "/tmp/in/manifest.json",
                       "--inputs", "/tmp/in", "--out", "/kaggle/working/out", "--engine-set", {engine_set!r},
                       "--expect-batch", {test_id!r}]).returncode
print("worker exit code", code)
'''


def notebook_ref(p: Project) -> str:
    """The test's own notebook, apart from the film's worker: <user>/<film>-finish-test."""
    return f"{settings(p)['username']}/{p.name}-finish-test"


def render_clip(p: Project, shot_id: str) -> Path | None:
    """The shot's 3D render that its guides came from (the same render, without a guide's suffix)."""
    folder = cgi_config.work_dir(p, cgi_config.settings(p), shot_id)
    found = [f for f in (folder / f"{shot_id}.mp4", folder / f"{shot_id}-preview.mp4") if f.exists()]
    return max(found, key=lambda f: f.stat().st_mtime) if found else None


def build(p: Project, shot_id: str, engine: str, controls: list[str], work: Path, release: Release,
          minutes: int = 120, engine_set: str = "gpu") -> dict:
    """The test's inputs and notebook, in work/<test id>: one finish job per guide clip."""
    s = p.shot(shot_id)
    cfg = steps.finish_config(p, engine)
    if not cfg:
        raise ValueError(f"no engines.{engine} in the film's config.json")
    test_id = time.strftime(f"ft-{shot_id}-{engine}-%Y%m%d-%H%M%S", time.gmtime())
    specs = []
    for n, control in enumerate(controls):
        clip = steps.guide_clip(p, shot_id, control)
        if clip is None:
            raise FileNotFoundError(f"{shot_id} has no {control} guide: run `cgi render {shot_id} --guides` first")
        spec = steps.finish_spec(p, s, n, clip, engine, control)
        if spec is None:
            raise FileNotFoundError(f"{shot_id} has no reference stills to be painted from (style_bible/refs)")
        per_second = float(cfg.get("gpu_seconds_per_output_second", 400))
        spec.update(key=f"{test_id}-{control}", est_seconds=per_second * s.seconds, guide=control)
        specs.append(spec)
    folder = work / test_id
    jobs = pack(p, specs, folder, {"batch_id": test_id, "stage": "ai_finish", "chapter": s.chapter,
                                   "backend": NAME, "deadline_seconds": minutes * 60 - 600,
                                   "slow_factor": 100})
    data = folder / "dataset"
    archive = folder / f"{test_id}-inputs.tar.gz"
    with tarfile.open(archive, "w:gz") as t:
        for f in sorted(data.iterdir()):
            t.add(f, arcname=f.name)
    ref = notebook_ref(p)
    kern = folder / "kernel"
    (kern / "finish_test.py").write_text(SCRIPT.format(
        film=p.name, test_id=test_id, url=release.url(archive.name), engine_set=engine_set,
        packages=", ".join(repr(x) for x in WORKER_PACKAGES)))
    (kern / "kernel-metadata.json").write_text(json.dumps({
        "id": ref, "title": ref.split("/", 1)[1], "code_file": "finish_test.py", "language": "python",
        "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
        "enable_internet": "true", "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}, indent=1))
    return {"test_id": test_id, "folder": folder, "archive": archive, "kernel": kern, "ref": ref,
            "jobs": jobs, "data": data, "engine": engine, "shot": shot_id, "settings": cfg}


def _ff(args: list[str]) -> None:
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *args], check=True)


def side_by_side(render: Path | None, guide: Path, finish: Path, out: Path, fps: int) -> Path:
    """The 3D render, its guide and the finish, side by side at the finish's frame rate."""
    w, h = TILE
    clips = [c for c in (render, guide, finish) if c is not None]
    args: list[str] = []
    for c in clips:
        args += ["-i", str(c)]
    chains = [f"[{i}:v]fps={fps},scale={w}:{h}:force_original_aspect_ratio=decrease,"
              f"pad={w}:{h}:(ow-iw)/2:(oh-ih)/2,setsar=1,format=yuv420p[v{i}]" for i in range(len(clips))]
    stack = "".join(f"[v{i}]" for i in range(len(clips))) + f"hstack=inputs={len(clips)}[out]"
    _ff([*args, "-filter_complex", ";".join([*chains, stack]), "-map", "[out]", "-shortest",
         "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-pix_fmt", "yuv420p", str(out)])
    return out


def middle_frame(render: Path | None, finish: Path, refs: list[Path], out: Path, seconds: float,
                 height: int) -> Path:
    """One moment of the shot: the 3D render, the finish, then the stills it was painted from."""
    args: list[str] = []
    sources = [c for c in (render, finish) if c is not None]
    for c in sources:
        args += ["-ss", f"{seconds / 2:.2f}", "-i", str(c)]
    for r in refs:
        args += ["-i", str(r)]
    n = len(sources) + len(refs)
    chains = [f"[{i}:v]scale=-2:{height},setsar=1,format=rgb24[v{i}]" for i in range(n)]
    stack = "".join(f"[v{i}]" for i in range(n)) + (f"hstack=inputs={n}[out]" if n > 1 else "null[out]")
    _ff([*args, "-filter_complex", ";".join([*chains, stack]), "-map", "[out]", "-frames:v", "1", str(out)])
    return out


def compare(p: Project, t: dict, out: Path, results: dict) -> list[Path]:
    """Side-by-sides and middle frames of every finish that came back."""
    s = p.shot(t["shot"])
    cfg = t["settings"]
    made: list[Path] = []
    render = render_clip(p, s.id)
    for job in t["jobs"]:
        r = results.get("jobs", {}).get(job["key"]) or {}
        clip = next(iter(out.rglob(r["file"])), None) if r.get("ok") and r.get("file") else None
        if clip is None:
            continue
        guide = t["data"] / job["control"]
        refs = [t["data"] / x for x in job.get("refs", [])]
        base = t["folder"] / job["key"]
        finished = base.with_suffix(".mp4")
        shutil.copyfile(clip, finished)
        made += [finished,
                 side_by_side(render, guide, finished, base.with_name(base.name + "-side.mp4"), int(cfg["fps"])),
                 middle_frame(render, finished, refs, base.with_name(base.name + "-middle.png"), s.seconds,
                              int(cfg["height"]))]
    return made


def summary(t: dict, results: dict, statuses: list[str], minutes: float) -> dict:
    s_jobs = {}
    for job in t["jobs"]:
        r = results.get("jobs", {}).get(job["key"]) or {}
        gpu = r.get("gpu_seconds")
        s_jobs[job["guide"]] = {"ok": bool(r.get("ok")), "error": r.get("error"), "gpu_seconds": gpu,
                                "gpu_seconds_per_output_second": round(gpu / job["seconds"]) if gpu else None,
                                "frames": r.get("frames"), "size": f"{r.get('width')}x{r.get('height')}"
                                if r.get("width") else None}
    return {"test": t["test_id"], "shot": t["shot"], "engine": t["engine"], "model": t["settings"]["model"],
            "notebook": t["ref"], "statuses": statuses, "minutes": round(minutes, 1),
            "engine_load_seconds": {k: v.get("load_seconds") for k, v in results.get("groups", {}).items()},
            "load_errors": {k: v["load_error"][-1500:] for k, v in results.get("groups", {}).items()
                            if v.get("load_error")},
            "error": results.get("error"), "jobs": s_jobs}


def run(p: Project, kgc, release: Release, shot_id: str, engine: str, controls: list[str], work: Path,
        minutes: int = 120, poll: int = 60, sleep=time.sleep, engine_set: str = "gpu") -> dict:
    """Build, upload, run on Kaggle, fetch, compare, upload the results. Returns the summary."""
    t = build(p, shot_id, engine, controls, work, release, minutes, engine_set)
    release.ensure(NOTES)
    release.upload(t["archive"])
    print(f"{t['test_id']}: {len(t['jobs'])} job(s); inputs at {release.url(t['archive'].name)}", flush=True)
    t0, st = time.time(), "queued"
    seen: list[str] = []
    try:
        kgc.push(t["kernel"], p.config[NAME].get("accelerator", DEFAULT_ACCELERATOR), minutes * 60)
    except KaggleError as e:                             # e.g. Kaggle's two GPU sessions are taken
        s = summary(t, {"error": f"the notebook was not started: {e}"}, ["not started"], 0.0)
        s_file = t["folder"] / f"{t['test_id']}-summary.json"
        s_file.write_text(json.dumps(s, indent=1))
        release.upload(s_file)
        s["files"] = [release.url(s_file.name)]
        return s
    while time.time() - t0 < (minutes + 60) * 60:            # Kaggle's queue comes on top of the run
        sleep(poll)
        st = kgc.status(t["ref"])
        if not seen or seen[-1] != st:
            seen.append(st)
            print(f"{(time.time() - t0) / 60:5.1f} min  {st}", flush=True)
        if st in ("complete", "error", "cancelled"):
            break
    out = t["folder"] / "out"
    try:
        kgc.output(t["ref"], out)
    except KaggleError as e:
        print(f"no output: {e}", flush=True)
    res_f = next(out.rglob("results.json"), None) if out.exists() else None
    results = json.loads(res_f.read_text()) if res_f else {}
    made = compare(p, t, out, results)
    s = summary(t, results, seen, (time.time() - t0) / 60)
    s_file = t["folder"] / f"{t['test_id']}-summary.json"
    s_file.write_text(json.dumps(s, indent=1))
    logs = [f for f in (next(out.rglob("worker.jsonl"), None) if out.exists() else None,
                        next(out.glob("*.log"), None) if out.exists() else None) if f is not None]
    for f in logs:
        shutil.copyfile(f, t["folder"] / f"{t['test_id']}-{f.name}")
    files = [*made, s_file, *(t["folder"] / f"{t['test_id']}-{f.name}" for f in logs)]
    for f in files:
        release.upload(f)
    s["files"] = [release.url(f.name) for f in files]
    return s
