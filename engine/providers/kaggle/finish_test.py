from .provider import DEFAULT_ACCELERATOR, NAME, KaggleError, settings

RELEASE = "finish-tests"
NOTES = ("AI finish tests, one shot at a time, outside the production ledger (python -m engine finish-test, "
         ".github/workflows/finish-test.yml): each test's inputs, finished clips, side-by-sides and log.")
TILE = (640, 360)              # each picture's size in a side-by-side video
BACKENDS = ("kaggle", "colab")
COLAB = "colab"                # the Colab runner's prefix in the batches release (engine/providers/colab)
COLAB_PICKUP_MINUTES = 75      # the runner looks every 30 minutes; after this the test takes its batch down

SCRIPT = '''# {film} AI finish test {test_id}. Generated by `python -m engine finish-test`; do not edit.
import os, shutil, subprocess, sys, tarfile, urllib.request
os.environ.setdefault("HF_HOME", "/tmp/hf")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
os.makedirs("/tmp/in", exist_ok=True)
urllib.request.urlretrieve({url!r}, "/tmp/inputs.tar.gz")
with tarfile.open("/tmp/inputs.tar.gz") as t:
    t.extractall("/tmp/in")
for tool in (["nvidia-smi"], ["free", "-g"], ["df", "-h", "/tmp", "/kaggle/working"]):
    if shutil.which(tool[0]):
        subprocess.run(tool)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", {packages}], check=True)
os.makedirs("/kaggle/working/out", exist_ok=True)
code = subprocess.run([sys.executable, "/tmp/in/worker.py", "--manifest", "/tmp/in/manifest.json",
                       "--inputs", "/tmp/in", "--out", "/kaggle/working/out", "--engine-set", {engine_set!r},
                       "--expect-batch", {test_id!r}]).returncode
print("worker exit code", code)
'''


def notebook_ref(p: Project) -> str:
    """The test's own notebook, apart from the film's worker: <user>/<film>-finish-test."""
    return f"{settings(p)['username']}/{p.name}-finish-test"


def render_clip(p: Project, shot_id: str) -> Path | None:
    """The shot's 3D render that its guides came from (the same render, without a guide's suffix)."""
    folder = cgi_config.work_dir(p, cgi_config.settings(p), shot_id)
    found = [f for f in (folder / f"{shot_id}.mp4", folder / f"{shot_id}-preview.mp4") if f.exists()]
    return max(found, key=lambda f: f.stat().st_mtime) if found else None


def build(p: Project, shot_id: str, engines: list[str], controls: list[str], work: Path, release: Release,
          minutes: int = 120, engine_set: str = "gpu") -> dict:
    """The test's inputs, in work/<test id>: one finish job per engine and guide clip; the archive for
    Kaggle (with the worker) and the one for Colab's runner (which brings its own)."""
    s = p.shot(shot_id)
    for engine in engines:
        if not steps.finish_config(p, engine):
            raise ValueError(f"no engines.{engine} in the film's config.json")
    test_id = time.strftime(f"ft-{shot_id}-%Y%m%d-%H%M%S", time.gmtime())
    specs: list[dict] = []
    for engine in engines:
        per_second = float(steps.finish_config(p, engine).get("gpu_seconds_per_output_second", 400))
        for control in controls:
            clip = steps.guide_clip(p, shot_id, control)
            if clip is None:
                raise FileNotFoundError(f"{shot_id} has no {control} guide: run `cgi render {shot_id} --guides`")
            spec = steps.finish_spec(p, s, len(specs), clip, engine, control)
            if spec is None:
                raise FileNotFoundError(f"{shot_id} has no reference stills to be painted from (style_bible/refs)")
            spec.update(key=f"{test_id}-{engine}-{control}", est_seconds=per_second * s.seconds, guide=control)
            specs.append(spec)
    folder = work / test_id
    jobs = pack(p, specs, folder, {"batch_id": test_id, "stage": "ai_finish", "chapter": s.chapter,
                                   "backend": NAME, "deadline_seconds": minutes * 60 - 600,
                                   "slow_factor": 100})
    data = folder / "dataset"
    archive = folder / f"{test_id}-inputs.tar.gz"
    colab_archive = folder / batch_names(test_id, COLAB)["inputs"]
    with tarfile.open(archive, "w:gz") as t, tarfile.open(colab_archive, "w:gz") as c:
        for f in sorted(data.iterdir()):
            t.add(f, arcname=f.name)
            if f.name != "worker.py":                   # the Colab runner sends its own copy
                c.add(f, arcname=f.name)
    ref = notebook_ref(p)
    kern = folder / "kernel"
    (kern / "finish_test.py").write_text(SCRIPT.format(
        film=p.name, test_id=test_id, url=release.url(archive.name), engine_set=engine_set,
        packages=", ".join(repr(x) for x in WORKER_PACKAGES)))
    (kern / "kernel-metadata.json").write_text(json.dumps({
        "id": ref, "title": ref.split("/", 1)[1], "code_file": "finish_test.py", "language": "python",
        "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
        "enable_internet": "true", "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}, indent=1))
    return {"test_id": test_id, "folder": folder, "archive": archive, "colab_archive": colab_archive,
            "kernel": kern, "ref": ref, "jobs": jobs, "data": data, "engines": engines, "shot": shot_id}


def _ff(args: list[str]) -> None:
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *args], check=True)


def side_by_side(render: Path | None, guide: Path, finish: Path, out: Path, fps: int) -> Path:
    """The 3D render, its guide and the finish, side by side at the finish's frame rate."""
    w, h = TILE
    clips = [c for c in (render, guide, finish) if c is not None]
    args: list[str] = []
    for c in clips:
        args += ["-i", str(c)]
    chains = [f"[{i}:v]fps={fps},scale={w}:{h}:force_original_aspect_ratio=decrease,"
              f"pad={w}:{h}:(ow-iw)/2:(oh-ih)/2,setsar=1,format=yuv420p[v{i}]" for i in range(len(clips))]
    stack = "".join(f"[v{i}]" for i in range(len(clips))) + f"hstack=inputs={len(clips)}[out]"
    _ff([*args, "-filter_complex", ";".join([*chains, stack]), "-map", "[out]", "-shortest",
         "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-pix_fmt", "yuv420p", str(out)])
    return out


def middle_frame(render: Path | None, finish: Path, refs: list[Path], out: Path, seconds: float,
                 height: int) -> Path:
    """One moment of the shot: the 3D render, the finish, then the stills it was painted from."""
    args: list[str] = []
    sources = [c for c in (render, finish) if c is not None]
    for c in sources:
        args += ["-ss", f"{seconds / 2:.2f}", "-i", str(c)]
    for r in refs:
        args += ["-i", str(r)]
    n = len(sources) + len(refs)
    chains = [f"[{i}:v]scale=-2:{height},setsar=1,format=rgb24[v{i}]" for i in range(n)]
    stack = "".join(f"[v{i}]" for i in range(n)) + (f"hstack=inputs={n}[out]" if n > 1 else "null[out]")
    _ff([*args, "-filter_complex", ";".join([*chains, stack]), "-map", "[out]", "-frames:v", "1", str(out)])
    return out


def compare(p: Project, t: dict, out: Path, results: dict) -> list[Path]:
    """Side-by-sides and middle frames of every finish that came back."""
    s = p.shot(t["shot"])
    made: list[Path] = []
    render = render_clip(p, s.id)
    for job in t["jobs"]:
        r = results.get("jobs", {}).get(job["key"]) or {}
        clip = next(iter(out.rglob(r["file"])), None) if r.get("ok") and r.get("file") else None
        if clip is None:
            continue
        cfg = steps.finish_config(p, job["engine"])
        guide = t["data"] / job["control"]
        refs = [t["data"] / x for x in job.get("refs", [])]
        base = t["folder"] / job["key"]
        finished = base.with_suffix(".mp4")
        shutil.copyfile(clip, finished)
        made += [finished,
                 side_by_side(render, guide, finished, base.with_name(base.name + "-side.mp4"), int(cfg["fps"])),
                 middle_frame(render, finished, refs, base.with_name(base.name + "-middle.png"), s.seconds,
                              int(cfg["height"]))]
    return made


def summary(p: Project, t: dict, results: dict, statuses: list[str], minutes: float, backend: str) -> dict:
    s_jobs = {}
    for job in t["jobs"]:
        r = results.get("jobs", {}).get(job["key"]) or {}
        gpu = r.get("gpu_seconds")
        s_jobs[f"{job['engine']}/{job['guide']}"] = {
            "ok": bool(r.get("ok")), "error": r.get("error"), "gpu_seconds": gpu,
            "gpu_seconds_per_output_second": round(gpu / job["seconds"]) if gpu else None,
            "frames": r.get("frames"), "size": f"{r.get('width')}x{r.get('height')}" if r.get("width") else None}
    return {"test": t["test_id"], "shot": t["shot"], "backend": backend,
            "engines": {e: steps.finish_config(p, e)["model"] for e in t["engines"]},
            "where": t["ref"] if backend == "kaggle" else f"the {COLAB} runner (batches release)",
            "gpu": results.get("gpu"), "units_used": results.get("units_used"),
            "vm_seconds": results.get("vm_seconds"), "statuses": statuses, "minutes": round(minutes, 1),
            "engine_load_seconds": {k: v.get("load_seconds") for k, v in results.get("groups", {}).items()},
            "load_errors": {k: v["load_error"][-1500:] for k, v in results.get("groups", {}).items()
                            if v.get("load_error")},
            "error": results.get("error"), "jobs": s_jobs}


def _results(out: Path) -> dict:
    found = next(out.rglob("results.json"), None) if out.exists() else None
    return json.loads(found.read_text()) if found else {}


def _on_kaggle(p: Project, kgc, t: dict, minutes: int, poll: int, sleep) -> tuple[dict, list[str], str | None]:
    """Push the notebook, wait for it, download its output. (results, statuses, why it never started)."""
    try:
        kgc.push(t["kernel"], p.config[NAME].get("accelerator", DEFAULT_ACCELERATOR), minutes * 60)
    except KaggleError as e:                             # e.g. Kaggle's two GPU sessions are taken
        return {}, ["not started"], f"the notebook was not started: {e}"
    t0, seen = time.time(), list[str]()
    while time.time() - t0 < (minutes + 60) * 60:        # Kaggle's queue comes on top of the run
        sleep(poll)
        st = kgc.status(t["ref"])
        if not seen or seen[-1] != st:
            seen.append(st)
            print(f"{(time.time() - t0) / 60:5.1f} min  {st}", flush=True)
        if st in ("complete", "error", "cancelled"):
            break
    out = t["folder"] / "out"
    try:
        kgc.output(t["ref"], out)
    except KaggleError as e:
        print(f"no output: {e}", flush=True)
    return _results(out), seen, None


def _on_colab(t: dict, batches: Release, minutes: int, poll: int, sleep) -> tuple[dict, list[str], str | None]:
    """Leave the inputs for the Colab runner, wait for its results, take the batch's files down."""
    n = batch_names(t["test_id"], COLAB)
    batches.ensure()
    batches.upload(t["colab_archive"])
    print(f"{n['inputs']} waits in the batches release for the Colab runner (every 30 min)", flush=True)
    t0, seen = time.time(), list[str]()
    st = "waiting"
    while True:
        sleep(poll)
        waited = (time.time() - t0) / 60
        a = batches.assets()
        if a:                                            # {}: GitHub did not answer; ask again
            st = ("done" if n["results"] in a else "running" if n["claim"] in a
                  else "waiting" if n["inputs"] in a else "gone")
            if not seen or seen[-1] != st:
                seen.append(st)
                print(f"{waited:5.1f} min  {st}", flush=True)
        if st == "done":
            break
        if st == "gone" and len(seen) > 1:
            return {}, seen, "the batch's files were taken down before its results came back"
        if st != "running" and waited > COLAB_PICKUP_MINUTES:
            batches.delete(n["inputs"])                  # never left behind for a later run to spend units on
            return {}, seen, f"no Colab runner took the batch in {COLAB_PICKUP_MINUTES} min; it was taken down"
        if waited > minutes + 120:
            return {}, seen, "the Colab run took too long to report; its results stay in the batches release"
    out = t["folder"] / "out"
    out.mkdir(parents=True, exist_ok=True)
    if n["results"] in a:
        tgz = out / n["results"]
        batches.download(a[n["results"]], tgz)
        with tarfile.open(tgz) as tar:
            try:
                tar.extractall(out, filter="data")
            except TypeError:                            # Python before 3.11.4
                tar.extractall(out)
    for name in n.values():
        if name in a:
            batches.delete(name)
    return _results(out), seen, None


def run(p: Project, kgc, release: Release, shot_id: str, engines: list[str], controls: list[str], work: Path,
        minutes: int = 120, poll: int = 60, sleep=time.sleep, engine_set: str = "gpu", backend: str = "kaggle",
        batches: Release | None = None) -> dict:
    """Build, run on Kaggle or Colab, fetch, compare, upload the results. Returns the summary."""
    if backend not in BACKENDS:
        raise ValueError(f"backend must be one of {', '.join(BACKENDS)}")
    t = build(p, shot_id, engines, controls, work, release, minutes, engine_set)
    release.ensure(NOTES)
    release.upload(t["archive"])
    print(f"{t['test_id']}: {len(t['jobs'])} job(s) on {backend}; inputs at {release.url(t['archive'].name)}",
          flush=True)
    t0 = time.time()
    if backend == "kaggle":
        results, seen, why = _on_kaggle(p, kgc, t, minutes, poll, sleep)
    else:
        assert batches is not None, "Colab needs the batches release"
        results, seen, why = _on_colab(t, batches, minutes, poll, sleep)
    if why:
        results = {**results, "error": why}
    made = compare(p, t, t["folder"] / "out", results)
    s = summary(p, t, results, seen, (time.time() - t0) / 60, backend)
    s_file = t["folder"] / f"{t['test_id']}-summary.json"
    s_file.write_text(json.dumps(s, indent=1))
    out = t["folder"] / "out"
    logs = [f for f in ((next(out.rglob("worker.jsonl"), None), next(out.glob("*.log"), None))
                        if out.exists() else ()) if f is not None]
    for f in logs:
        shutil.copyfile(f, t["folder"] / f"{t['test_id']}-{f.name}")
    files = [*made, s_file, *(t["folder"] / f"{t['test_id']}-{f.name}" for f in logs)]
    for f in files:
        release.upload(f)
    s["files"] = [release.url(f.name) for f in files]
    return s
