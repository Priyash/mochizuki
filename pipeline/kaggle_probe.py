"""A one-off engine test on a Kaggle T4, outside the ledger: a few jobs in a separate notebook
(`mochizuki-probe`), with the worker and its manifest embedded in the script (no dataset).

    python -m pipeline kaggle-probe --variants fp16,fp32

Each variant makes the same reference still ("style") with the refs engine at that precision,
so one run tells whether the T4 can make stills, where it breaks if not, and how long a still takes.
"""
from __future__ import annotations

import base64
import copy
import json
import time
from pathlib import Path

from . import kaggle as kg
from .project import Project

SCRIPT = '''# mochizuki engine probe. Generated by `python -m pipeline kaggle-probe`; do not edit.
import base64, os, subprocess, sys
os.environ.setdefault("HF_HOME", "/tmp/hf")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
os.makedirs("/tmp/in", exist_ok=True)
open("/tmp/in/worker.py", "wb").write(base64.b64decode({worker!r}))
open("/tmp/in/manifest.json", "wb").write(base64.b64decode({manifest!r}))
subprocess.run([sys.executable, "-m", "pip", "install", "-q", {packages}], check=True)
os.makedirs("/kaggle/working/out", exist_ok=True)
code = subprocess.run([sys.executable, "/tmp/in/worker.py", "--manifest", "/tmp/in/manifest.json",
                       "--inputs", "/tmp/in", "--out", "/kaggle/working/out", "--engine-set", "gpu",
                       "--expect-batch", {batch_id!r}]).returncode
print("worker exit code", code)
'''


def build(p: Project, work: Path, variants: list[str], ref: str = "style", minutes: int = 60) -> tuple[Path, str]:
    batch_id = time.strftime("probe-%Y%m%d-%H%M%S")
    style_text = (p.root / "style_bible" / "style.txt").read_text(encoding="utf-8").strip() \
        if (p.root / "style_bible" / "style.txt").exists() else ""
    r = next(x for x in p.ref_plan() if x["name"] == ref)
    prompt = "\n".join(x for x in (style_text, r["prompt"]) if x)
    engines = copy.deepcopy(p.config["engines"])
    jobs = []
    for v in variants:
        name = "refs" if v == "config" else f"refs_{v}"
        if name != "refs":
            engines[name] = {**copy.deepcopy(engines["refs"]), "dtype": v}
            if v == "fp32":                       # activations and dequantised weights are twice as big
                engines[name]["vram_headroom_gb"] = engines["refs"].get("vram_headroom_gb", 2.5) + 1.5
        jobs.append({"key": f"probe-{ref}-{v}", "shot_id": f"probe-{ref}", "kind": "ref", "idx": len(jobs),
                     "engine": name, "prompt": prompt, "width": r.get("width", 1664),
                     "height": r.get("height", 928), "est_seconds": 900})
    manifest = {"batch_id": batch_id, "stage": "refs", "chapter": 0, "backend": "kaggle",
                "deadline_seconds": minutes * 60 - 300, "slow_factor": 100, "engines": engines, "jobs": jobs}
    folder = work / batch_id
    folder.mkdir(parents=True, exist_ok=True)
    worker = (Path(kg.WORKER)).read_bytes()
    (folder / "probe.py").write_text(SCRIPT.format(
        worker=base64.b64encode(worker).decode(), manifest=base64.b64encode(json.dumps(manifest).encode()).decode(),
        packages=", ".join(repr(x) for x in kg.PACKAGES), batch_id=batch_id))
    user = p.config["kaggle"]["username"]
    ref_id = f"{user}/mochizuki-probe"
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": ref_id, "title": "mochizuki-probe", "code_file": "probe.py", "language": "python",
        "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
        "enable_internet": "true", "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}, indent=1))
    return folder, ref_id


def run(p: Project, kgc, work: Path, variants: list[str], minutes: int = 60, poll: int = 60, sleep=time.sleep) -> dict:
    folder, ref = build(p, work, variants, minutes=minutes)
    kgc.push(folder, p.config["kaggle"].get("accelerator", "NvidiaTeslaT4"), minutes * 60)
    t0, st, seen = time.time(), "queued", []
    while time.time() - t0 < (minutes + 45) * 60:              # queue time on top of the run itself
        sleep(poll)
        st = kgc.status(ref)
        if not seen or seen[-1] != st:
            seen.append(st)
            print(f"{(time.time() - t0) / 60:5.1f} min  {st}", flush=True)
        if st in ("complete", "error", "cancelled"):
            break
    out = work / "out"
    try:
        kgc.output(ref, out)
    except kg.KaggleError as e:
        print(f"no output: {e}")
    res_f = next(out.rglob("results.json"), None)
    res = json.loads(res_f.read_text()) if res_f else {}
    return {"kernel": ref, "status": st, "statuses": seen, "minutes": round((time.time() - t0) / 60, 1),
            "jobs": res.get("jobs", {}), "groups": res.get("groups", {}), "error": res.get("error"),
            "files": sorted(str(f.relative_to(out)) for f in out.rglob("*") if f.is_file())}
