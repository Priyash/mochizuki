# ---------------------------------------------------------------- talking to Kaggle
class KaggleCLI:
    """Thin wrapper over the `kaggle` command. `runner` is swappable for tests."""

    name = "kaggle"

    def __init__(self, runner=None):
        self._run = runner or self._subprocess
        self.log: list[str] = []          # what Kaggle said, for the run's status.json

    @staticmethod
    def _subprocess(args: list[str]) -> tuple[int, str]:
        if not shutil.which("kaggle"):
            raise KaggleError("the kaggle command is missing: pip install kaggle")
        r = subprocess.run(["kaggle", *args], capture_output=True, text=True)
        return r.returncode, (r.stdout or "") + (r.stderr or "")

    def call(self, *args: str) -> str:
        code, out = self._run(list(args))
        self.log.append(f"kaggle {' '.join(args[:2])} -> {code}: {out.strip()[-400:]}")
        if code != 0 or "error" in out.lower():
            raise KaggleError(f"kaggle {' '.join(args[:3])} failed: {out.strip()[-500:]}")
        return out

    def dataset_status(self, ref: str) -> str:
        code, out = self._run(["datasets", "status", ref])
        self.last_status = f"{code}: {out.strip()[-300:]}"
        self.log.append(f"kaggle datasets status {ref} -> {self.last_status}")
        if code != 0 and ("404" in out or "403" in out or "not found" in out.lower()):   # Kaggle answers 403 for a dataset that does not exist
            return "missing"
        return out.strip().lower() if code == 0 else f"unknown ({out.strip()[-200:]})"

    LICENSES = ("unknown", "other", "copyright-authors")      # all keep every right with the owner

    def publish_dataset(self, folder: Path, ref: str, message: str) -> None:
        if self.dataset_status(ref) == "missing":
            meta_f = folder / "dataset-metadata.json"
            meta = json.loads(meta_f.read_text())
            for lic in self.LICENSES:
                meta["licenses"] = [{"name": lic}]
                meta_f.write_text(json.dumps(meta, indent=1))
                try:
                    self.call("datasets", "create", "-p", str(folder), "-q")
                    return
                except KaggleError as e:
                    if "license" not in str(e).lower():
                        raise
            raise KaggleError(f"Kaggle accepted none of the licences {self.LICENSES} for the private dataset")
        else:
            self.call("datasets", "version", "-p", str(folder), "-m", message, "-q")

    def wait_dataset_ready(self, ref: str, timeout: float = 900, poll: float = 15) -> None:
        end = time.time() + timeout
        while time.time() < end:
            st = self.dataset_status(ref)
            if "ready" in st:
                return
            if "error" in st:
                raise KaggleError(f"dataset {ref} failed to process: {st}")
            time.sleep(poll)
        raise KaggleError(f"dataset {ref} not ready after {timeout:.0f} s; last status "
                          f"{getattr(self, 'last_status', '?')}")

    def push(self, folder: Path, accelerator: str, timeout_s: int) -> None:
        self.call("kernels", "push", "-p", str(folder), "--accelerator", accelerator, "-t", str(timeout_s))

    def status(self, ref: str, handle: str | None = None) -> str:
        code, out = self._run(["kernels", "status", ref])
        self.log.append(f"kaggle kernels status -> {code}: {out.strip()[-300:]}")
        if code != 0:
            gone = any(w in out.lower() for w in ("404", "403", "not found", "denied", "wrong kernel slug"))
            return "error" if gone else "unknown"             # the notebook was deleted or is out of reach
        m = re.search(r'has status "([^"]+)"', out)
        s = (m.group(1) if m else out).lower()
        for word in ("complete", "error", "cancel", "running", "queued"):
            if word in s:
                return "cancelled" if word == "cancel" else word
        return "unknown"

    def output(self, ref: str, dest: Path, handle: str | None = None) -> None:
        dest.mkdir(parents=True, exist_ok=True)
        self.call("kernels", "output", ref, "-p", str(dest), "-o", "-q")

    def gpu_hours_left(self) -> float | None:
        code, out = self._run(["quota", "-v"])
        if code != 0:
            return None
        for line in out.splitlines():
            parts = [x.strip() for x in line.split(",")]
            if parts and parts[0].upper() == "GPU" and len(parts) >= 3:
                try:
                    return float(parts[2].rstrip("h"))
                except ValueError:
                    return None
        return None


class LocalKaggle:
    """A stand-in for Kaggle (or, with another name, for a second GPU backend) that runs the
    worker here with stub engines. Free and offline."""

    def __init__(self, root: Path, name: str = "kaggle"):
        self.name = name
        self.root = root
        self.datasets: dict[str, Path] = {}
        self.runs: dict[str, str] = {}
        self.outputs: dict[str, Path] = {}

    def publish_dataset(self, folder: Path, ref: str, message: str) -> None:
        self.datasets[ref] = folder

    def wait_dataset_ready(self, ref: str, **_) -> None:
        if ref not in self.datasets:
            raise KaggleError(f"dataset {ref} was never published")

    def push(self, folder: Path, accelerator: str, timeout_s: int) -> None:
        meta = json.loads((folder / "kernel-metadata.json").read_text())
        ref = meta["id"] + ("" if self.name == "kaggle" else f"-{self.name}")
        data = self.datasets[meta["dataset_sources"][0]] if self.name == "kaggle" else folder.parent / "dataset"
        out = self.root / "local_kaggle" / ref.replace("/", "_") / "out"
        shutil.rmtree(out, ignore_errors=True)
        batch = re.search(r"BATCH_ID = '([^']+)'", (folder / "bootstrap.py").read_text()).group(1)
        r = subprocess.run([sys.executable, str(data / "worker.py"), "--manifest", str(data / "manifest.json"),
                            "--inputs", str(data), "--out", str(out), "--engine-set", "stub",
                            "--expect-batch", batch], capture_output=True, text=True)
        self.runs[ref] = "complete" if r.returncode in (0, 3) else "error"
        self.outputs[ref] = out
        if r.returncode not in (0, 3):
            print(r.stdout[-2000:], r.stderr[-2000:])
        return ref

    def status(self, ref: str, handle: str | None = None) -> str:
        return self.runs.get(handle or ref, "unknown")

    def output(self, ref: str, dest: Path, handle: str | None = None) -> None:
        src = self.outputs.get(handle or ref)
        dest.mkdir(parents=True, exist_ok=True)
        if src and src.exists():
            shutil.copytree(src, dest / "out", dirs_exist_ok=True)

    def gpu_hours_left(self) -> float | None:
        return None

    def budget(self, p: Project, led: Ledger) -> tuple[float, float]:
        """Only used when this stand-in plays a second backend."""
        return session_budget(p), 300.0


# ---------------------------------------------------------------- batches
def _cfg(p: Project) -> dict:
    k = dict(p.config.get("kaggle", {}))
    if not k.get("username"):
        k["username"] = os.environ.get("KAGGLE_USERNAME", "")
    return k


def refs(p: Project) -> tuple[str, str]:
    k = _cfg(p)
    if not k["username"]:
        raise KaggleError("set kaggle.username in config.json (or KAGGLE_USERNAME)")
    return f"{k['username']}/{k['dataset_slug']}", f"{k['username']}/{k['kernel_slug']}"


def week_start(now: float | None = None) -> float:
    """Kaggle's GPU week resets on Saturday at 00:00 UTC (its quota reports refreshAt)."""
    now = time.time() if now is None else now
    t = time.gmtime(now)
    days_since_saturday = (t.tm_wday - 5) % 7
    midnight = now - (t.tm_hour * 3600 + t.tm_min * 60 + t.tm_sec)
    return midnight - days_since_saturday * 86400


def session_budget(p: Project) -> float:
    k = _cfg(p)
    return k.get("session_hours", 10) * 3600 - k.get("setup_minutes", 25) * 60


class BudgetUsedUp(KaggleError):
    """A backend's free allowance for this week or month is spent. Not an error: it rests."""


def backend_budget(p: Project, led: Ledger, backend: str, kg=None) -> tuple[float, float]:
    """(GPU seconds the next batch may use, setup seconds) inside a backend's free allowance.

    Kaggle's comes from config.json; any other backend object brings its own budget(p, led).
    """
    if backend != "kaggle":
        if kg is None or not hasattr(kg, "budget"):
            raise KaggleError(f"backend {backend} does not say how much GPU time it has")
        return kg.budget(p, led)
    k = _cfg(p)
    setup = k.get("setup_minutes", 25) * 60
    used = led.gpu_seconds_since(week_start(), "kaggle")
    weekly = k.get("weekly_gpu_hours", 28) * 3600
    budget = min(session_budget(p), weekly - used - setup)
    if budget <= 600:
        raise BudgetUsedUp(f"this week's Kaggle GPU budget is used up ({used / 3600:.1f} h of "
                           f"{weekly / 3600:.0f} h); it resets Saturday 00:00 UTC")
    return budget, setup


def build(p: Project, led: Ledger, stage: str, chapter: int, only: str | None = None,
          engine_set: str = "gpu", backend: str = "kaggle", kg=None) -> dict:
    """Reserve the next batch of jobs and pack everything one GPU session needs."""
    if stage not in STAGES:
        raise ValueError(f"stage must be one of {STAGES}")
    if led.active_batch(backend):
        raise KaggleError(f"batch {led.active_batch(backend)['id']} is still open; run `collect` first")
    k = _cfg(p)
    dataset_ref, kernel_ref = refs(p) if backend == "kaggle" else (f"{backend}/mochizuki", f"{backend}/mochizuki-worker")
    budget, setup = backend_budget(p, led, backend, kg)
    batch_id = time.strftime("b%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:4]
    ex = steps.BatchExecutor(batch_id, budget)
    fn = {"refs": steps.refs, "keyframes": steps.keyframes, "video": steps.video, "upscale": steps.upscale}[stage]
    summary = fn(p, led, ex, chapter, only)
    if not ex.specs:
        return {"batch": None, "stage": stage, "summary": summary}

    # pack: every input file flattened into one folder, renamed so names cannot clash
    work = p.media / "batches" / batch_id
    data, kern = work / "dataset", work / "kernel"
    data.mkdir(parents=True)
    kern.mkdir(parents=True)
    names: dict[str, str] = {}

    def ship(path: str) -> str:
        src = p.fetch(path)
        if str(src) not in names:
            if not src.exists():
                raise KaggleError(f"input {src} is missing")
            name = f"{len(names):04d}_{src.name}"
            shutil.copyfile(src, data / name)
            names[str(src)] = name
        return names[str(src)]

    jobs = []
    for spec in ex.specs:
        job = dict(spec)
        if spec.get("refs"):
            job["refs"] = [ship(r) for r in spec["refs"]]
        for field in ("image", "source"):
            if spec.get(field):
                job[field] = ship(spec[field])
        jobs.append(job)
    manifest = {"batch_id": batch_id, "stage": stage, "chapter": chapter, "backend": backend,
                "deadline_seconds": budget + setup - (900 if backend == "kaggle" else 300),
                "engines": p.config["engines"], "jobs": jobs}
    (data / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    shutil.copyfile(WORKER, data / "worker.py")
    (data / "dataset-metadata.json").write_text(json.dumps(
        {"title": k["dataset_slug"], "id": dataset_ref, "licenses": [{"name": "unknown"}]}, indent=1))
    (kern / "bootstrap.py").write_text(BOOTSTRAP.format(
        batch_id=batch_id, engine_set=engine_set, packages=", ".join(repr(x) for x in PACKAGES)))
    (kern / "kernel-metadata.json").write_text(json.dumps({
        "id": kernel_ref, "title": k["kernel_slug"], "code_file": "bootstrap.py", "language": "python",
        "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
        "enable_internet": "true", "dataset_sources": [dataset_ref], "competition_sources": [],
        "kernel_sources": [], "model_sources": []}, indent=1))
    led.create_batch(batch_id, stage, chapter, ex.est + setup, backend=backend)
    return {"batch": batch_id, "backend": backend, "stage": stage, "jobs": len(jobs), "deferred": ex.deferred,
            "est_hours": round((ex.est + setup) / 3600, 2), "summary": summary}


def discard(led: Ledger, batch_id: str, why: str) -> None:
    """Drop a batch that was never submitted. Its jobs are freed and do not count as failures."""
    for job in led.batch_jobs(batch_id):
        if job["status"] == "pending":
            led.finish(job["key"], None, ok=False, note="not reached")
    led.set_batch(batch_id, status="failed", note=why, finished_at=time.time())


def submit(p: Project, led: Ledger, kg, batch_id: str) -> dict:
    b = led.batch(batch_id)
    if not b or b["status"] != "built":
        raise KaggleError(f"batch {batch_id} is not waiting to be submitted")
    if b["stage"] == "keyframes" and not p.references():
        discard(led, batch_id, "no reference stills")
        raise KaggleError("batch dropped: no reference stills. Add at least style_bible/refs/style.png")
    k = _cfg(p)
    kaggle = b["backend"] == "kaggle"
    dataset_ref, _ = refs(p) if kaggle else (f"{b['backend']}/mochizuki", "")
    work = p.media / "batches" / batch_id
    left = kg.gpu_hours_left()
    if left is not None and left * 3600 < b["est_seconds"] * 0.5:
        raise KaggleError(f"Kaggle says {left:.1f} GPU h left this week; batch needs ~{b['est_seconds'] / 3600:.1f} h")
    kg.publish_dataset(work / "dataset", dataset_ref, batch_id)
    kg.wait_dataset_ready(dataset_ref)
    if kaggle:
        timeout = int(min(12 * 3600, k.get("session_hours", 10) * 3600 + 1800))
        handle = kg.push(work / "kernel", k.get("accelerator", "NvidiaTeslaT4"), timeout)
    else:                                   # hard stop just past the batch's own budget: it cannot overspend
        timeout = int(b["est_seconds"] + 1200)
        handle = kg.push(work / "kernel", getattr(kg, "accelerator", ""), timeout)
    led.set_batch(batch_id, status="submitted", submitted_at=time.time(),
                  handle=handle if isinstance(handle, str) else None)
    return {"batch": batch_id, "backend": b["backend"], "submitted": True}


def collect(p: Project, led: Ledger, kg, batch_id: str) -> dict:
    """If the run has finished, download it and record every job. Safe to call repeatedly."""
    b = led.batch(batch_id)
    if not b or b["status"] != "submitted":
        raise KaggleError(f"batch {batch_id} is not running")
    kernel_ref = refs(p)[1] if b["backend"] == "kaggle" else f"{b['backend']}/mochizuki-worker"
    st = kg.status(kernel_ref, handle=b["handle"])
    if st in ("queued", "running", "unknown"):
        return {"batch": batch_id, "backend": b["backend"], "status": st}
    work = p.media / "batches" / batch_id
    try:
        kg.output(kernel_ref, work / "download", handle=b["handle"])
    except KaggleError:
        pass                                   # nothing to download: its jobs are freed below
    found = list((work / "download").rglob("results.json"))
    results = json.loads(found[0].read_text(encoding="utf-8")) if found else {"jobs": {}, "error": "no results.json"}
    stale = results.get("batch_id") not in (None, batch_id) or "stale" in str(results.get("error") or "")
    outdir = found[0].parent if found else work / "download"
    made = failed = left = 0
    for job in led.batch_jobs(batch_id):
        if job["status"] != "pending":
            continue
        r = results.get("jobs", {}).get(job["key"]) if not stale else None
        if r and r.get("ok") and (outdir / r["file"]).exists():
            dest = steps.out_path(p, job["shot_id"], job["kind"], job["key"], Path(r["file"]).suffix)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(outdir / r["file"]), dest)
            led.finish(job["key"], p.rel(dest), gpu_seconds=r.get("gpu_seconds"))
            made += 1
        elif r:
            led.finish(job["key"], None, ok=False, gpu_seconds=r.get("gpu_seconds"),
                       note=("oom: " if r.get("oom") else "") + str(r.get("error"))[:180])
            failed += 1
        else:
            led.finish(job["key"], None, ok=False, note="stale inputs" if stale else "not reached")
            left += 1
    elapsed = results.get("elapsed")
    led.set_batch(batch_id, status="done" if st == "complete" else "failed", finished_at=time.time(),
                  gpu_seconds=results.get("vm_seconds") if results.get("vm_seconds") is not None
                  else (elapsed + 300) if elapsed else None,           # + pip install before the worker
                  note=(results.get("error") or st)[:200] if (results.get("error") or st != "complete") else None)
    return {"batch": batch_id, "backend": b["backend"], "status": st, "made": made, "failed": failed,
            "not_reached": left,
            "stale": stale, "error": results.get("error")}


def next_stage(p: Project, led: Ledger, chapter: int) -> str | None:
    """What the chapter needs next from the GPU, or None if it is waiting on a person."""
    missing = p.refs_missing(chapter)
    if any(steps.ref_state(p, led, r) in ("todo", "needs_candidates") for r in missing):
        return "refs"
    if missing:
        return None                      # gate 1: the reference stills are not approved yet
    states = [steps.state(p, led, s) for s in p.chapter(chapter)]
    if any(s in ("todo", "needs_keyframes") for s in states):
        return "keyframes"
    if led.approved(chapter, "board") and any(s in ("needs_take", "needs_variants") for s in states):
        return "video"
    if led.approved(chapter, "animatic") and any(
            steps.upscale_state(p, led, s) == "needed" for s in p.chapter(chapter)):
        return "upscale"
    return None


def tick(p: Project, led: Ledger, kg, chapter: int, engine_set: str = "gpu", can_hand_over: bool = False) -> dict:
    """One automation step: collect a finished run, or start the next one. Cron calls this."""
    name = getattr(kg, "name", "kaggle")
    active = led.active_batch(name)
    if active and active["status"] == "built" and \
            not (p.media / "batches" / active["id"] / "dataset" / "manifest.json").exists():
        discard(led, active["id"], "packed on another machine")     # e.g. an earlier GitHub run; repack
        active = None
    if active:
        if active["status"] == "built":
            try:
                return {"action": "submitted", **submit(p, led, kg, active["id"])}
            except Exception:
                discard(led, active["id"], f"could not be submitted to {name}")
                raise
        res = collect(p, led, kg, active["id"])
        stuck = _cfg(p).get("max_queue_hours", 3) * 3600
        if can_hand_over and name == "kaggle" and res["status"] == "queued" and \
                time.time() - (active["submitted_at"] or time.time()) > stuck and \
                (can_hand_over(active["stage"]) if callable(can_hand_over) else True):
            discard(led, active["id"], "stuck in Kaggle's queue; handed to the other backend")
            return {"action": "handed_over", "backend": name, "batch": active["id"],
                    "reason": f"queued on Kaggle for over {stuck / 3600:.0f} h"}
        if res["status"] in ("queued", "running", "unknown"):
            return {"action": "waiting", **res}
        return {"action": "collected", **res}
    stage = next_stage(p, led, chapter)
    allowed = getattr(kg, "stages", None)
    if stage and allowed and stage not in allowed and \
            not (getattr(kg, "take_over", False) and kaggle_stuck(led)):
        return {"action": "idle", "backend": name,
                "reason": f"{stage} is not run on {name}: config {name}.stages only takes {', '.join(allowed)}"}
    if stage is None:
        queue = steps.review_queue(p, led, chapter)
        return {"action": "idle", "reason": "waiting for a person", "to_review": len(queue),
                "states": steps.status(p, led, chapter)["states"]}
    broken = engine_broken(led, name, stage)
    if broken:
        return {"action": "resting", "backend": name, "reason": broken}
    try:
        built = build(p, led, stage, chapter, engine_set=engine_set, backend=name, kg=kg)
    except BudgetUsedUp as e:
        return {"action": "resting", "backend": name, "reason": str(e)}
    if not built["batch"]:
        return {"action": "idle", "reason": f"nothing to run for {stage}", **built}
    try:
        return {"action": "built_and_submitted", **built, **submit(p, led, kg, built["batch"])}
    except Exception:
        discard(led, built["batch"], f"could not be submitted to {name}")   # free the jobs for the other backend
        raise


def code_time() -> float:
    """When the checked-out code was committed (0 if unknown)."""
    try:
        r = subprocess.run(["git", "-C", str(REPO), "log", "-1", "--format=%ct"], capture_output=True, text=True)
        return float(r.stdout.strip() or 0)
    except (OSError, ValueError):
        return 0.0


def engine_broken(led: Ledger, backend: str, stage: str, runs: int = 2) -> str | None:
    """If the last `runs` batches of this stage on this backend made nothing at all because of
    machine errors (engine would not load, out of memory, CUDA), say so: running again would only
    spend GPU time. A code or config change is needed; any new commit earns a fresh try."""
    rows = led.db.execute("SELECT id FROM batches WHERE backend=? AND stage=? AND status IN ('done','failed')"
                          " AND created_at > ? ORDER BY created_at DESC LIMIT ?",
                          (backend, stage, code_time(), runs)).fetchall()
    if len(rows) < runs:
        return None
    first = None
    for r in rows:
        jobs = led.batch_jobs(r["id"])
        tried = [j for j in jobs if (j["note"] or "") not in ("not reached", "stale inputs", "cut off")]
        if not tried or any(j["status"] == "done" for j in jobs) or \
                not all(not_a_failure(j["note"]) for j in tried):
            return None
        first = first or tried[0]["note"]
    return (f"the {stage} engine made nothing in the last {runs} {backend} batches (machine errors); "
            f"stopped until the next code change: {first[:300]}")


def someone_else_can_take(p: Project, led: Ledger, backends: list, me, stage: str) -> bool:
    """Another backend would take this stage now: allowed to (its stages, or it takes over from a
    stuck Kaggle) and within its budget (Colab: the agreed unit cap). Otherwise a batch
    stuck in Kaggle's queue keeps its place instead of being dropped for nothing."""
    for other in backends:
        if other is me:
            continue
        allowed = getattr(other, "stages", None)
        if allowed and stage not in allowed and not getattr(other, "take_over", False):
            continue
        try:
            if hasattr(other, "budget"):
                other.budget(p, led)
            return True
        except Exception:  # noqa: BLE001 - resting, no credit, no stock: it can't take it
            continue
    return False


def kaggle_stuck(led: Ledger) -> bool:
    """Kaggle's latest batch was handed over because it sat in Kaggle's queue too long."""
    row = led.db.execute("SELECT status, note FROM batches WHERE backend='kaggle'"
                         " ORDER BY created_at DESC LIMIT 1").fetchone()
    return bool(row) and row["status"] == "failed" and (row["note"] or "").startswith("stuck in Kaggle")


def tick_all(p: Project, led: Ledger, backends: list, chapter: int, engine_set: str = "gpu") -> list[dict]:
    """One automation step on every backend: each collects its finished run, then starts the next.

    Each backend holds at most one open batch. Jobs are reserved when a batch is packed, so two
    backends never make the same job; the second one takes what the first left.
    """
    out = []
    for b in led.active_batches():                      # repack what an earlier run packed
        if b and b["status"] == "built" and \
                not (p.media / "batches" / b["id"] / "dataset" / "manifest.json").exists():
            discard(led, b["id"], "packed on another machine")
    for kg in backends:                                 # paid machines nobody tracks are deleted first
        if hasattr(kg, "cleanup"):
            try:
                n = kg.cleanup(led)
                if n:
                    out.append({"action": "cleaned_up", "backend": kg.name, "pods_deleted": n})
            except Exception as e:  # noqa: BLE001
                out.append({"action": "error", "backend": kg.name, "error": f"cleanup: {e}"[:300]})
    for kg in backends:
        for _ in range(4):                                  # collect, then start the next in the same run
            try:
                r = tick(p, led, kg, chapter, engine_set=engine_set,
                         can_hand_over=lambda stage, me=kg: someone_else_can_take(p, led, backends, me, stage))
            except Exception as e:  # noqa: BLE001 - one backend failing must not stop the other
                r = {"action": "error", "error": f"{type(e).__name__}: {e}"[:500]}
            r.setdefault("backend", getattr(kg, "name", "kaggle"))
            out.append(r)
            if r["action"] != "collected":
                break                       # after a handover Kaggle waits a run, so the other backend takes it
    return out
