"""Kaggle batches: pack inputs, push one GPU run, collect what it made.

One batch = one Kaggle session (up to `session_hours`). Inputs travel as one private
Kaggle dataset, versioned per batch; the worker code travels with them. Kaggle's
own command-line tool does the talking, so nothing here needs a Kaggle SDK.

LocalKaggle stands in for Kaggle in tests and `--kaggle local`: it runs the worker
on this machine with stub engines, so the whole loop can be exercised for free.
"""
